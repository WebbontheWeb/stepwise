/*
 * Files Stepwise adds to a test case folder so Claude (and other AI agents) can work in it.
 * Keys are paths inside that folder. Stepwise only writes a file if it's missing, so edits are kept.
 */
(function (root) {
  'use strict';

  const AGENTS_MD = `# Test cases (Stepwise)

This folder holds manual test cases for Azure DevOps (ADO) Test Plans. People edit them in the
Stepwise desktop app and copy them into ADO. You can read, review and edit these files directly.
Stepwise reloads changed files straight away and lets the user keep or undo each change.

## Layout

- \`cases/<id>.md\`: one test case per file. The file name is the case id.
- \`blocks/<id>.md\`: reusable step blocks (like ADO Shared Steps). The file name is the block id.
- \`stepwise.json\`: settings (the ADO project URL). Leave it alone unless asked.
- \`.claude/commands/\`: the /audit, /draft-case and /find-blocks commands.

## Test case format

\`\`\`markdown
---
title: Report over $500 requires manager approval
ado_id:                       # ADO work item id once it exists in ADO; blank for new cases
suite: Expenses / Approvals
area: Project\\Expenses
priority: 2                   # 1-4
state: Design                 # Design | Ready | Closed
assigned:
tags: [expenses, approvals]
tests: [1201]                 # ADO ids of the requirements/user stories this case covers
related: [expense-approval-routing]   # ids of related cases in cases/ (list it on both cases)
---

## Description

What this case proves. May use **bold** and *italic*.

## Preconditions

Accounts, data and settings the steps rely on.

## Steps

1. [Use block: Log in as an employee] \`#k3f9 use:log-in-as-employee\`
2. Add a "Hotel" line for **$600** \`#m8q4\`
   Expected: An "Approval required" banner appears above the total
3. Select Submit \`#r5d2\`
   Expected: Status changes to *Pending approval*
4. [Repeat steps 2–3] as a manager \`#t7w2 repeat:m8q4..r5d2\`
   Expected: No banner appears and the report is submitted
\`\`\`

### Rules for steps

- The code span at the end of a step's first line holds its id (\`#k3f9\`) and, for references,
  what it points at. **Ids are the source of truth; step numbers and bracketed labels are
  regenerated by Stepwise.** Never change an existing id.
- For a new step, invent a 4-character id (lowercase letters and digits) unique in the file, or
  leave the code span off and Stepwise assigns one.
- \`use:<block-id>\` inserts every step of \`blocks/<block-id>.md\` at that point.
- \`repeat:<from-id>..<to-id>\` repeats an earlier range of steps in the same case. The range must
  come before the repeat step. Text after the bracket is a note, e.g. "as a manager".
- A multi-line action or expected result continues on lines indented by three spaces.
- \`Repeat steps 2-3\` or \`Use block: <block title>\` without a code span also work; Stepwise resolves
  them when it loads the file.

### Formatting

Step text, expected results, descriptions and preconditions may use **bold** and *italic*
(Markdown \`**bold**\` and \`*italic*\`). Write a literal asterisk as \`\\*\`. Don't use other Markdown
inside steps (no links, headings or lists).

## Block format

\`\`\`markdown
---
title: Log in as an employee
---

## Description

When to use this block.

## Steps

1. Go to the sign-in page \`#a1aa\`
   Expected: The sign-in page loads
\`\`\`

Blocks contain plain steps only (no nested blocks or repeats). Changing a block changes every case
that uses it: search for \`use:<block-id>\` to see which.

## Writing good test cases

- One action per step, written as an instruction ("Select Submit"), naming the exact control or data.
- Every action step has an expected result a tester can observe: specific text, a status, a value.
  Never "works correctly" or "as expected".
- Preconditions list the accounts, data and settings the steps rely on.
- Use blocks for setup that several cases share (signing in, creating a record) instead of copying steps.
- Use a repeat step instead of rewriting a sequence within one case.
- Across a set of cases, cover negative paths, boundaries (just under, at and just over a limit) and
  permissions, not just the happy path.
- Titles say what the case proves ("Report over $500 requires manager approval"), not "Approval test".
- Keep \`tests:\` pointing at requirement ids, and list related cases on both sides.

## Working in this folder

- Small fixes you're asked for are fine. Ask before deleting files or making sweeping changes.
- New cases: \`state: Design\`, \`ado_id\` blank, file name a short kebab-case version of the title.
- Never put real credentials or personal data in test cases; refer to test accounts by name.
`;

  const CLAUDE_MD = `# Claude Code

Instructions for this folder live in AGENTS.md, which other AI tools read too.

@AGENTS.md
`;

  const AUDIT = `---
description: Review test cases for clarity, completeness and coverage gaps
argument-hint: "[case id, suite, requirement id, or blank for all]"
---

Review these test cases: $ARGUMENTS (if blank, review everything in cases/).

Use "Writing good test cases" in AGENTS.md as the standard. For each case, check that:

- every action step has one clear action and a specific, observable expected result
- the steps are in order and nothing needed to reach a state is missing
- the preconditions cover the accounts, data and settings the steps assume
- block and repeat references make sense where they're used

Across the set, look for missing negative paths, boundaries and permission checks, duplicated or
overlapping cases, and cases that should be related or linked to a requirement.

Report findings grouped by case, most important first, with a suggested rewrite for each weak step.
Don't edit anything yet: ask which fixes to apply, then make them in the files.
`;

  const DRAFT = `---
description: Draft new test cases from a user story or acceptance criteria
argument-hint: "<user story, acceptance criteria, or what to test>"
---

Draft manual test cases for: $ARGUMENTS

1. Read AGENTS.md, then look at the existing cases and blocks so the new cases match their style and
   reuse blocks where they fit.
2. If the request includes an ADO work item id, put it in \`tests:\`.
3. Cover the main path plus the important negative paths and boundaries. Several small cases are
   usually better than one long one.
4. Before writing anything, list the cases you plan (title and one line each) and any new blocks,
   and ask for a go-ahead.
5. Then create the files in cases/ (and blocks/ if needed) with \`state: Design\` and a blank
   \`ado_id\`, and list related cases on both sides.
`;

  const FIND_BLOCKS = `---
description: Find repeated steps that should become reusable blocks
---

Look through cases/ for runs of two or more steps that appear, word for word or nearly, in several
cases, and for existing blocks that cases could use but don't.

For each candidate, show the steps, which cases contain them, and a suggested block name. Ask before
changing anything. Once approved, create the block in blocks/ and replace those steps in each case
with a \`use:\` step. Keep the ids of the remaining steps unchanged, and fix any \`repeat:\` range that
pointed at a replaced step so it points at the new \`use:\` step.
`;

  const files = {
    'AGENTS.md': AGENTS_MD,
    'CLAUDE.md': CLAUDE_MD,
    '.claude/commands/audit.md': AUDIT,
    '.claude/commands/draft-case.md': DRAFT,
    '.claude/commands/find-blocks.md': FIND_BLOCKS,
  };

  // Earlier versions of Stepwise wrote the whole format guide into CLAUDE.md. That file is safe to
  // replace with the short version, as long as nobody has turned it into something else.
  function isOldClaudeMd(text) {
    return /^# Stepwise test cases\n/.test(text) && !text.includes('@AGENTS.md');
  }

  const api = { files, isOldClaudeMd };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.StepwiseWorkspace = api;
})(typeof window !== 'undefined' ? window : globalThis);
